//! naivi-wasm — generic U5/U7 wasm channel for the naivi (Vue Vapor) frontend.
//!
//! A `cdylib` exposing the binary-frame transport as wasm-bindgen exports
//! (U7): the guest queues DOM changes into a [`FrameWriter`] and flushes one
//! frame per boundary via [`flush_frame`]; events return per-callback via
//! [`set_event_callback`], and whole-frame rejections arrive via
//! [`set_frame_rejected_callback`] (self-heal, R15). A single
//! [`NaiviDocument`] is created by [`start`] and driven by
//! [`BlitzApplication`] (winit + VelloHybrid renderer on the `#blitz-target`
//! canvas).
//!
//! This is the SHARED wasm host: `nv wasm --release` (in any
//! `examples/naivi/<demo>`) drops the demo's guest bundle into this crate's
//! `assets/guest/`, and `trunk serve` (here) runs it. There are no per-demo
//! host crates.
//!
//! ## Protocol notes (shared with `js/naivi-runtime/src/wasm-types.ts`)
//!
//! - DOM changes: one binary frame per flush (`[seq u32][count u16][op…]`,
//!   virtual u32 node ids — KD3). No per-op exports.
//! - Event kinds are encoded as `u8`, matching [`NaiviEventKind`]'s generated
//!   `to_u8`/`from_u8` (click=0 … input=11); the JS side mirrors that in
//!   `EVENT_KINDS` (the `@naivi/protocol` SOT).
//! - `set_event_callback` receives `(nodeId, kind, x, y, key, code, value)` per
//!   drained event (nodeId = the JS-assigned virtual id; key/code for keyboard
//!   events, the full value for `input`).
//! - `set_frame_rejected_callback` receives `(seq, reason)` when a whole frame
//!   is discarded (KTD3).

